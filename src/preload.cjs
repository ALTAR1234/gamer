const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('nexus', {
  library: () => ipcRenderer.invoke('library'),
  scan: () => ipcRenderer.invoke('scan'),
  launch: (id) => ipcRenderer.invoke('launch', id),
  addFiles: (files) => ipcRenderer.invoke('add-files', files ? files.map((f) => webUtils.getPathForFile(f)) : null),
  update: (id, patch) => ipcRenderer.invoke('update', id, patch),
  remove: (id) => ipcRenderer.invoke('remove', id),
  setCover: (id, kind) => ipcRenderer.invoke('set-cover', id, kind),
  reveal: (id) => ipcRenderer.invoke('reveal', id),
  importArt: (id, file, pos) => ipcRenderer.invoke('import-art', id, file, pos),
  fullscreen: () => ipcRenderer.send('fullscreen'),
  openExternal: (url) => ipcRenderer.invoke('open-external', url),
  captures: () => ipcRenderer.invoke('captures'),
  openCaptures: () => ipcRenderer.invoke('captures:open'),
  revealCapture: (f) => ipcRenderer.invoke('captures:reveal', f),
  openXbox: () => ipcRenderer.invoke('xbox:open'),
  gamePass: (force) => ipcRenderer.invoke('gamepass', force),
  xbox: {
    status: () => ipcRenderer.invoke('xbl:status'),
    setClient: (id) => ipcRenderer.invoke('xbl:set-client', id),
    clearClient: () => ipcRenderer.invoke('xbl:clear-client'),
    signIn: () => ipcRenderer.invoke('xbl:sign-in'),
    cancel: () => ipcRenderer.invoke('xbl:cancel'),
    signOut: () => ipcRenderer.invoke('xbl:sign-out'),
    data: () => ipcRenderer.invoke('xbl:data'),
    onCode: (cb) => ipcRenderer.on('xbl:code', (_e, info) => cb(info)),
  },
  openGamePass: (productId) => ipcRenderer.invoke('gamepass:open', productId),
  setCollections: (id, names) => ipcRenderer.invoke('collections:set', id, names),
  deleteCollection: (name) => ipcRenderer.invoke('collections:delete', name),
  onLibrary: (cb) => ipcRenderer.on('library', (_e, lib) => cb(lib)),
  onRunning: (cb) => ipcRenderer.on('running', (_e, id) => cb(id)),
  onScanned: (cb) => ipcRenderer.on('scanned', (_e, r) => cb(r)),
});
